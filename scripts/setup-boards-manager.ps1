#Requires -Version 5.1
[CmdletBinding()]
param([string]$ToolchainPath, [string]$DfuToolPath,
      [string]$DfuInstallDirectory = (Join-Path $env:LOCALAPPDATA 'UC3Bduino/tools/dfu-programmer-1.1.0'), [ValidateRange(1,65535)][int]$UsbVendorId,
      [ValidateRange(1,65535)][int]$UsbProductId)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'installation-common.ps1')
if ($PSBoundParameters.ContainsKey('UsbVendorId') -ne $PSBoundParameters.ContainsKey('UsbProductId')) {
    throw 'Supply both authorized USB IDs together.'
}
if (-not $ToolchainPath -and -not $env:AVR32_TOOLCHAIN_PATH -and -not (Get-Command avr32-gcc.exe -ErrorAction SilentlyContinue)) {
    $candidate = Join-Path ${env:ProgramFiles(x86)} 'Atmel/AVR Tools/AVR32 Toolchain'
    if (Test-Path -LiteralPath $candidate) { $ToolchainPath = $candidate }
}
$compiler = Resolve-Uc3Toolchain $ToolchainPath
$settings = Join-Path (Split-Path -Parent $PSScriptRoot) 'platform.local.txt'
$marker = '# Generated by UC3Bduino setup-boards-manager.ps1'
if ((Test-Path -LiteralPath $settings) -and (Get-Content -LiteralPath $settings -TotalCount 1) -ne $marker) {
    throw "Custom settings already exist at $settings. Back them up before running setup."
}
if (-not $DfuToolPath) { $DfuToolPath = $env:UC3B_DFU_TOOL_PATH }
if (-not $DfuToolPath) {
    $cmd = Get-Command dfu-programmer.exe -CommandType Application -ErrorAction SilentlyContinue
    if ($cmd) { $DfuToolPath = $cmd.Source }
}
if (-not $DfuToolPath) {
    if (-not (Test-Path -LiteralPath $DfuInstallDirectory)) {
        & (Join-Path $PSScriptRoot 'get-dfu-tool.ps1') -Destination $DfuInstallDirectory
        if (-not $?) { throw 'The verified DFU download or extraction failed.' }
    }
    $DfuToolPath = $DfuInstallDirectory
}
$dfu = Test-Uc3DfuTool $DfuToolPath
$lines = @($marker, ('compiler.path=' + $compiler.Bin.Replace('\','/') + '/'))
$lines += 'tools.uc3bdfu.path=' + $dfu.Replace('\','/')
if ($PSBoundParameters.ContainsKey('UsbVendorId')) {
    $lines += "build.usb_flags=-DUC3BDUINO_USB_VENDOR_ID=$UsbVendorId -DUC3BDUINO_USB_PRODUCT_ID=$UsbProductId"
}
[IO.File]::WriteAllLines($settings, $lines, (New-Object Text.UTF8Encoding($false)))
Write-Host $compiler.Version
Write-Host "Configured $settings. Restart Arduino IDE."
